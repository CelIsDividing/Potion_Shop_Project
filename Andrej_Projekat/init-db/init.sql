CREATE TABLE transactions (
    id            BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT         NOT NULL,
    order_id      BIGINT         NOT NULL,
    card_id       BIGINT,
    amount        DECIMAL(10,2)  NOT NULL,
    paid_at       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_trans_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_trans_card FOREIGN KEY (card_id) REFERENCES cards(id) ON DELETE SET NULL
);

CREATE TABLE payment_items (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id  BIGINT         NOT NULL,
    order_item_id   BIGINT         NOT NULL,
    description     VARCHAR(500)   NOT NULL,
    amount          DECIMAL(10,2)  NOT NULL,
    CONSTRAINT fk_payment_trans FOREIGN KEY (transaction_id) REFERENCES transactions(id) ON DELETE CASCADE
);

