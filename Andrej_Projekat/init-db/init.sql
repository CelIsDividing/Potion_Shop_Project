-- ============================================================
-- PostgreSQL schema + seed data for the Potion Shop.
--
-- Run this ONCE against an existing, empty database that you are
-- already connected to (PostgreSQL has no "USE"/"CREATE DATABASE"
-- inside a script). For example:
--     psql "postgresql://USER:PASSWORD@HOST:5432/potionShop" -f init.sql
